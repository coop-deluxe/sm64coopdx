manual_function_types = {
    'boolean':  '`bool`',
    'integer':  '`integer`',
    'number':   '`number`',
    'string':   '`string`',
    'table':    '`table`',
    'function': '`function`',
    'fun':      '`function`',
    'nil':      '`nil`',
    'any':      '`any`',
}

def read_single_type(buffer: str):
    ptype = ''
    depth = 0
    for i, c in enumerate(buffer):
        if c in '<(':
            depth += 1
        elif c in '>)':
            depth = max(depth - 1, 0)
        elif depth == 0:
            if c.isalnum() or c in '_[]':
                ptype += c
            else:
                return ptype, buffer[i:]
    return ptype, ''

def read_type_and_description(line: str):
    ptype = ''
    pdesc = ''
    is_param = True
    is_function_return = False

    while line:
        stype, line = read_single_type(line)
        if stype:
            if is_function_return:
                is_function_return = False
                continue
            if is_param:
                ptype += stype
                is_param = False
            else:
                pdesc = stype + line
                break
        elif line[0] == ':':
            is_function_return = True
            line = line[1:]
        elif line[0] == ',':
            is_function_return = True
            line = line[1:]
        elif line[0] == '|':
            ptype += '|'
            is_param = True
            line = line[1:]
        else:
            line = line[1:]

    return ptype.strip(), pdesc.strip()

def get_empty_function_definition():
    return {
        'identifier': '',
        'params': [],
        'returns': [],
        'description': [],
        'lua_example': [],
    }

def read_manually_written_functions(in_filename):
    with open(in_filename, 'r', encoding='utf-8', newline='\n') as f:
        lines = f.readlines()

    classes = []
    functions = []
    function = get_empty_function_definition()
    text_type = None
    for line in lines:

        # Custom table
        if line.startswith('--- @class'):
            tokens = [token for token in line.split() if token]
            classes.append(tokens[2])

        # Parameter
        if line.startswith('--- @param'):
            tokens = [token for token in line.split() if token]
            ptype, pdesc = read_type_and_description(' '.join(tokens[3:]))
            function['params'].append({
                'name': tokens[2].strip('?'),
                'type': ptype,
                'desc': pdesc,
                'is_vararg': False,
            })
            text_type = 'description'

        # Vararg parameter
        elif line.startswith('--- @vararg'):
            tokens = [token for token in line.split() if token]
            ptype, pdesc = read_type_and_description(' '.join(tokens[2:]))
            ptokens = pdesc.split() or ['']
            function['params'].append({
                'name': ptokens[0],
                'type': ptype,
                'desc': " ".join(ptokens[1:]),
                'is_vararg': True,
            })
            text_type = 'description'

        # Return value
        elif line.startswith('--- @return'):
            tokens = [token for token in line.split() if token]
            rtype, rdesc = read_type_and_description(' '.join(tokens[2:]))
            rtokens = rdesc.split() or ['']
            function['returns'].append({
                'name': rtokens[0],
                'type': rtype,
                'desc': " ".join(rtokens[1:]),
            })
            text_type = 'description'

        # End of function doc
        elif line.startswith('function '):
            tokens = [token for token in line.replace('(', ' ').split() if token]
            function['identifier'] = tokens[1]
            function['description'] = '\n'.join(function['description']).strip('\n').split('\n')
            function['lua_example'] = '\n'.join(function['lua_example']).strip('\n').split('\n')
            functions.append(function)
            function = get_empty_function_definition()
            text_type = None

        # Lua example in doc
        elif line.startswith('--- ### Lua Example'):
            text_type = 'lua_example'

        # Doc
        elif line.startswith('---') and text_type:
            line_desc = line[4:].rstrip()
            function[text_type].append(line_desc)

        # Anything else
        else:
            function = get_empty_function_definition()
            text_type = None

    return functions, classes

enums_file = ''
def function_type_is_enum(ptype):
    global enums_file
    if not enums_file:
        with open(get_path(enums_filename), 'r', encoding='utf-8', newline='\n') as f:
            enums_file = f.read()

    return '@alias {ptype}\n'.format(ptype=ptype) in enums_file

def get_manual_function_type(ptype: str, classes, docs_dir):
    types = ptype.split('|')
    converted_types = []
    for t in types:
        type_str = ''
        if t.endswith('[]'):
            type_str += '`table` of '
            t = t[:-2]
        if t in manual_function_types:
            type_str += manual_function_types[t]
        elif t in classes:
            type_str += manual_function_types['table']
        elif t == 'SyncTable':
            type_str += '[SyncTable]({docs_dir}/globals.md#gGlobalSyncTable)'.format(docs_dir=docs_dir)
        elif function_type_is_enum(t):
            type_str += '[enum {t}]({docs_dir}/constants.md#enum-{t})'.format(t=t, docs_dir=docs_dir)
        else:
            type_str += '[{t}]({docs_dir}/structs.md#{t})'.format(t=t, docs_dir=docs_dir)
        converted_types.append(type_str)

    return ' \\| '.join(converted_types)

def doc_manual_function(function, classes, docs_dir, include_param_desc):
    fid = function['identifier']
    s = '\n## [%s](#%s)\n' % (fid, fid)

    s += '\n### Description\n'
    for line in function['description']:
        s +=  f'{line}\n'

    s += '\n### Lua Example\n'
    for line in function['lua_example']:
        s +=  f'{line}\n'

    s += '\n### Parameters\n'
    if function['params']:
        if include_param_desc:
            s += '| Field | Type | Description |\n'
            s += '| ----- | ---- | ----------- |\n'
        else:
            s += '| Field | Type |\n'
            s += '| ----- | ---- |\n'
        for param in function['params']:
            pname = param['name']
            ptype = param['type']
            is_vararg = param['is_vararg']
            if include_param_desc:
                s += '| %s%s | %s | %s |\n' % (pname, ('...' if is_vararg else ''), get_manual_function_type(ptype, classes, docs_dir), param.get('desc', ''))
            else:
                s += '| %s%s | %s |\n' % (pname, ('...' if is_vararg else ''), get_manual_function_type(ptype, classes, docs_dir))
    else:
        s += '- None\n'

    s += '\n### Returns\n'
    if function['returns']:
        for ret in function['returns']:
            rname = ret['name']
            rtype = ret['type']
            if rname:
                s += '- %s: %s\n' % (rname, get_manual_function_type(rtype, classes, docs_dir))
            else:
                s += '- %s\n' % get_manual_function_type(rtype, classes, docs_dir)
    else:
        s += '- None\n'

    s += '\n[:arrow_up_small:](#)\n\n<br />\n'

    return s

def doc_page_link(page_num):
    if page_num == 1:
        return 'functions.md'
    else:
        return 'functions-%d.md' % page_num

def doc_function_index(processed_files, manual_functions):
    s = '# Supported Functions\n'

    if manual_functions:
        s += '\n- manually written functions\n'
        for function in manual_functions:
            s += '   - [{identifier}](#{identifier})\n'.format(identifier=function['identifier'])
        s += '\n<br />\n\n'

    for processed_file in processed_files:
        page_num = processed_file['page_num']
        s += '- %s\n' % processed_file['filename']
        for function in processed_file['functions']:
            if not function['implemented']:
                continue
            if not allowed_identifier(None, functions_hidden, processed_file['filename'], function['identifier']):
                continue

            s += '   - [%s](%s#%s)\n' % (function['identifier'], doc_page_link(page_num), function['identifier'])
        s += '\n<br />\n\n'

    return s

def doc_lua_func_param(param):
    s = 'LuaFunction('

    lfp = param['lua_function_params']
    first_lfp = True

    for lfp_type in lfp:
        if not first_lfp:
            lfp_type += ', '
        first_lfp = False

        lfp_type, lfp_link = translate_type_to_lua(lfp_type)

        if lfp_link:
            s += '[%s](%s)' % (lfp_type, lfp_link)
        else:
            s += lfp_type

    s += ')'
    return s

def doc_overloaded_function(fname, function):
    s = ''
    overload = function['overload']
    skip, cont = 0, 0
    for i, func in enumerate(overload):
        for line in doc_function(fname, func).splitlines():
            if skip > 0: skip -= 1; continue
            if cont > 0: cont -= 1
            else: line = line.replace(func['identifier'], function['identifier'])

            if "C Prototype" in line: cont = 1
            if i+1 != len(overload) and "(#)" in line:
                s += "---"
                skip = 2
                break

            s += line + '\n'

    return s

def doc_function(fname, function):
    if function.get('overload'):
        return doc_overloaded_function(fname, function)

    if not function['implemented']:
        return ''

    # debug print out lua nuke functions
    if len(sys.argv) >= 2 and sys.argv[1] == 'fuzz':
        output_fuzz_function(fname, function)

    if not allowed_identifier(None, functions_hidden, fname, function['identifier']):
        return ''

    fid = function['identifier']
    s = '\n## [%s](#%s)\n' % (fid, fid)

    description = function.get('description', [""])

    rtype, rlink = translate_type_to_lua(function['type'])
    param_str = ', '.join([x['identifier'] for x in function['params'] if 'RET' not in x])

    if description[0] != "":
        s += '\n### Description\n'
        for line in description:
            s +=  f'{line}\n'

    s += "\n### Lua Example\n"
    rvalues = []
    if rtype is not None:
        rid = rtype.replace('`', '').split(' ')[0]
        rid = rid[0].lower() + rid[1:]
        rvalues.append((rid + 'Value', rtype, rlink))

    fparams, freturns = split_function_parameters_and_returns(function)
    for param in freturns:
        ptype, plink = translate_type_to_lua(param['rtype'])
        rvalues.append((param['identifier'], ptype, plink))

    if rvalues:
        s += "`local %s = %s(%s)`\n" % (", ".join([id for id, _, _ in rvalues]), fid, param_str)
    else:
        s += "`%s(%s)`\n" % (fid, param_str)

    s += '\n### Parameters\n'
    if len(fparams) > 0:
        s += '| Field | Type |\n'
        s += '| ----- | ---- |\n'
        for param in fparams:
            pid = param['identifier']
            ptype = param['type']
            ptype, plink = translate_type_to_lua(ptype)

            # build lua function params
            if param['type'] == 'LuaFunction' and 'lua_function_params' in param:
                ptype = doc_lua_func_param(param)

            if plink:
                s += '| %s | [%s](%s) |\n'  % (pid, ptype, plink)
                continue

            s += '| %s | %s |\n'  % (pid, ptype)

    else:
        s += '- None\n'

    s += '\n### Returns\n'
    if len(rvalues) > 0:
        for _, ptype, plink in rvalues:
            if plink:
                s += '- [%s](%s)\n' % (ptype, plink)
            else:
                s += '- %s\n' % ptype
    else:
        s += '- None\n'


    s += '\n### C Prototype\n'
    s += '`%s`\n' % function['line'].strip()

    s += '\n[:arrow_up_small:](#)\n\n<br />\n'

    return s

def doc_functions(fname, functions):
    s = ''
    for function in functions:
        s += doc_function(fname, function)
    return s

def doc_files(processed_files):
    pages = {}
    page_num = 1
    page_len_limit = 150000
    extra_space = 25000

    s = '## [:rewind: Lua Reference](lua.md)\n\n'
    s += '---\n\n$[FUNCTION_NAV_HERE]\n\n---\n\n'
    s += '$[FUNCTION_INDEX_HERE]'

    manual_functions, classes = read_manually_written_functions(get_path(manually_written_functions_filename))
    if manual_functions:
        s += '\n---\n# manually written functions\n'
        for function in manual_functions:
            s += doc_manual_function(function, classes, ".", False)

    for processed_file in processed_files:
        s_file  = '\n---'
        s_file += '\n# functions from %s\n\n<br />\n\n' % processed_file['filename']
        s_file += doc_functions(processed_file['filename'], processed_file['functions'])

        if len(s) + len(s_file) + extra_space > page_len_limit:
            s += '---\n\n$[FUNCTION_NAV_HERE]\n\n'
            pages[page_num] = s
            s = '## [:rewind: Lua Functions](functions.md)\n\n'
            s += '---\n\n$[FUNCTION_NAV_HERE]\n\n'
            page_num += 1
            extra_space = 0

        s += s_file
        processed_file['page_num'] = page_num

    s += '\n---\n\n$[FUNCTION_NAV_HERE]\n\n'
    pages[page_num] = s

    for pnum in pages:
        buffer = pages[pnum]
        page_name = ''
        if pnum == 1:
            buffer = buffer.replace('$[FUNCTION_INDEX_HERE]', doc_function_index(processed_files, manual_functions))
            page_name = ''
        else:
            page_name = '-%d' % pnum

        # build up nav
        function_nav = ''
        if (pnum - 1) in pages:
            function_nav += '[< prev](%s) | ' % doc_page_link(pnum - 1)
        for pnum_nav in pages:
            if pnum_nav == pnum:
                function_nav += '%d' % pnum_nav
            else:
                function_nav += '[%d](%s)' % (pnum_nav, doc_page_link(pnum_nav))

            if (pnum_nav + 1) in pages:
                function_nav += ' | '
        if (pnum + 1) in pages:
            function_nav += ' | [next >](%s)' % doc_page_link(pnum + 1)

        buffer = buffer.replace('$[FUNCTION_NAV_HERE', function_nav)

        with open(get_path(out_filename_docs % page_name), 'w', encoding='utf-8', newline='\n') as out:
            out.write(buffer)

